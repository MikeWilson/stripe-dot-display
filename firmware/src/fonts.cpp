int bigIndex(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  switch (c) {
    case '$': return 10;  case '.': return 11;  case ',': return 12;
    case ':': return 13;  case 'k': case 'K': return 14;
    case 'M': case 'm': return 15;  case '-': return 16;
    case ' ': return 17;  case '%': return 18;
  }
  return -1;
}

